#!/usr/bin/env bash
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
source "$ROOT/benchmarks/paths.example.env"

BENCHMARK=${BENCHMARK:-bfcl_v4}
MODEL_FAMILY=${MODEL_FAMILY:-qwen3_8b}

case "$BENCHMARK" in
  bfcl_v4)
    BENCHMARK_NAME="BFCL V4"
    MODEL_GROUP=${MODEL_GROUP:-tool_use_qwen3_8b}
    BENCHMARK_RL_TRAIN_DATA=${BENCHMARK_RL_TRAIN_DATA:-$BFCL_V4_RL_TRAIN_DATA}
    BENCHMARK_CLIP_DATA=${BENCHMARK_CLIP_DATA:-$BFCL_V4_CLIP_DATA}
    BENCHMARK_PROMPT_MANIFEST=${BENCHMARK_PROMPT_MANIFEST:-$BFCL_V4_PROMPT_MANIFEST}
    BENCHMARK_SOURCE_ROOT=${BENCHMARK_SOURCE_ROOT:-$BFCL_V4_SOURCE_ROOT}
    BENCHMARK_ENGINE=${BENCHMARK_ENGINE:-tool_env}
    ;;
  tau2|tau2bench|tau2_bench)
    BENCHMARK=tau2_bench
    BENCHMARK_NAME="tau^2-Bench"
    MODEL_GROUP=${MODEL_GROUP:-tool_use_qwen3_8b}
    BENCHMARK_RL_TRAIN_DATA=${BENCHMARK_RL_TRAIN_DATA:-$TAU2_BENCH_RL_TRAIN_DATA}
    BENCHMARK_CLIP_DATA=${BENCHMARK_CLIP_DATA:-$TAU2_BENCH_CLIP_DATA}
    BENCHMARK_PROMPT_MANIFEST=${BENCHMARK_PROMPT_MANIFEST:-$TAU2_BENCH_PROMPT_MANIFEST}
    BENCHMARK_SOURCE_ROOT=${BENCHMARK_SOURCE_ROOT:-$TAU2_BENCH_SOURCE_ROOT}
    BENCHMARK_ENGINE=${BENCHMARK_ENGINE:-tool_env}
    ;;
  webshop)
    BENCHMARK_NAME="WebShop"
    MODEL_GROUP=${MODEL_GROUP:-webshop_qwen3_8b}
    BENCHMARK_RL_TRAIN_DATA=${BENCHMARK_RL_TRAIN_DATA:-$WEBSHOP_RL_TRAIN_DATA}
    BENCHMARK_CLIP_DATA=${BENCHMARK_CLIP_DATA:-$WEBSHOP_CLIP_DATA}
    BENCHMARK_PROMPT_MANIFEST=${BENCHMARK_PROMPT_MANIFEST:-$WEBSHOP_PROMPT_MANIFEST}
    BENCHMARK_SOURCE_ROOT=${BENCHMARK_SOURCE_ROOT:-$WEBSHOP_SOURCE_ROOT}
    BENCHMARK_ENGINE=${BENCHMARK_ENGINE:-sdar}
    ;;
  alfworld)
    BENCHMARK_NAME="ALFWorld"
    MODEL_GROUP=${MODEL_GROUP:-alfworld_qwen3_8b}
    BENCHMARK_RL_TRAIN_DATA=${BENCHMARK_RL_TRAIN_DATA:-$ALFWORLD_RL_TRAIN_DATA}
    BENCHMARK_CLIP_DATA=${BENCHMARK_CLIP_DATA:-$ALFWORLD_CLIP_DATA}
    BENCHMARK_PROMPT_MANIFEST=${BENCHMARK_PROMPT_MANIFEST:-$ALFWORLD_PROMPT_MANIFEST}
    BENCHMARK_SOURCE_ROOT=${BENCHMARK_SOURCE_ROOT:-$ALFWORLD_SOURCE_ROOT}
    BENCHMARK_ENGINE=${BENCHMARK_ENGINE:-sdar}
    ;;
  search_qa|searchqa)
    BENCHMARK=search_qa
    BENCHMARK_NAME="Search QA"
    MODEL_GROUP=${MODEL_GROUP:-search_qa_qwen3_8b}
    BENCHMARK_RL_TRAIN_DATA=${BENCHMARK_RL_TRAIN_DATA:-$SEARCH_QA_RL_TRAIN_DATA}
    BENCHMARK_CLIP_DATA=${BENCHMARK_CLIP_DATA:-$SEARCH_QA_CLIP_DATA}
    BENCHMARK_PROMPT_MANIFEST=${BENCHMARK_PROMPT_MANIFEST:-$SEARCH_QA_PROMPT_MANIFEST}
    BENCHMARK_SOURCE_ROOT=${BENCHMARK_SOURCE_ROOT:-$SEARCH_QA_SOURCE_ROOT}
    BENCHMARK_ENGINE=${BENCHMARK_ENGINE:-sdar}
    ;;
  *) echo "Unknown BENCHMARK=$BENCHMARK; expected bfcl_v4, tau2_bench, webshop, alfworld, or search_qa" >&2; exit 2 ;;
esac

case "$MODEL_FAMILY" in
  qwen3_8b)
    MODEL_FAMILY_LABEL=Qwen3-8B
    case "$MODEL_GROUP" in
      tool_use_qwen3_8b) MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN3_8B_TOOL_USE_MODEL} ;;
      webshop_qwen3_8b) MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN3_8B_WEBSHOP_MODEL} ;;
      alfworld_qwen3_8b) MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN3_8B_ALFWORLD_MODEL} ;;
      search_qa_qwen3_8b) MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN3_8B_SEARCH_QA_MODEL} ;;
      *) echo "MODEL_GROUP=$MODEL_GROUP is invalid for MODEL_FAMILY=$MODEL_FAMILY" >&2; exit 2 ;;
    esac
    ;;
  qwen3_5_4b|qwen35_4b)
    MODEL_FAMILY=qwen3_5_4b
    MODEL_FAMILY_LABEL=Qwen3.5-4B
    # The benchmark cases above use Qwen3-8B defaults for backwards
    # compatibility. Re-select the same benchmark group for Qwen3.5-4B.
    if [[ "${MODEL_GROUP:-}" == *_qwen3_8b ]]; then
      MODEL_GROUP=
    fi
    case "$BENCHMARK" in
      bfcl_v4|tau2_bench) MODEL_GROUP=${MODEL_GROUP:-tool_use_qwen3_5_4b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN35_4B_TOOL_USE_MODEL} ;;
      webshop) MODEL_GROUP=${MODEL_GROUP:-webshop_qwen3_5_4b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN35_4B_WEBSHOP_MODEL} ;;
      alfworld) MODEL_GROUP=${MODEL_GROUP:-alfworld_qwen3_5_4b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN35_4B_ALFWORLD_MODEL} ;;
      search_qa) MODEL_GROUP=${MODEL_GROUP:-search_qa_qwen3_5_4b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$QWEN35_4B_SEARCH_QA_MODEL} ;;
    esac
    ;;
  gemma4_12b)
    MODEL_FAMILY_LABEL=google/gemma-4-12B-it
    if [[ "${MODEL_GROUP:-}" == *_qwen3_8b ]]; then
      MODEL_GROUP=
    fi
    case "$BENCHMARK" in
      bfcl_v4|tau2_bench) MODEL_GROUP=${MODEL_GROUP:-tool_use_gemma4_12b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$GEMMA4_12B_TOOL_USE_MODEL} ;;
      webshop) MODEL_GROUP=${MODEL_GROUP:-webshop_gemma4_12b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$GEMMA4_12B_WEBSHOP_MODEL} ;;
      alfworld) MODEL_GROUP=${MODEL_GROUP:-alfworld_gemma4_12b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$GEMMA4_12B_ALFWORLD_MODEL} ;;
      search_qa) MODEL_GROUP=${MODEL_GROUP:-search_qa_gemma4_12b}; MODEL_SOURCE_PATH=${MODEL_SOURCE_PATH:-$GEMMA4_12B_SEARCH_QA_MODEL} ;;
    esac
    ;;
  *) echo "Unknown MODEL_FAMILY=$MODEL_FAMILY; expected qwen3_8b, qwen3_5_4b, or gemma4_12b" >&2; exit 2 ;;
esac

MODEL_PATH=${MODEL_PATH:-$MODEL_SOURCE_PATH}
TEACHER_MODEL=${TEACHER_MODEL:-$MODEL_SOURCE_PATH}
INITIAL_W4_MASTER=${INITIAL_W4_MASTER:-$MODEL_SOURCE_PATH}
MODEL_SERVING_NAME=${MODEL_SERVING_NAME:-$MODEL_FAMILY_LABEL}

export BENCHMARK BENCHMARK_NAME MODEL_FAMILY MODEL_FAMILY_LABEL MODEL_GROUP MODEL_SOURCE_PATH
export MODEL_PATH TEACHER_MODEL INITIAL_W4_MASTER MODEL_SERVING_NAME
export BENCHMARK_RL_TRAIN_DATA BENCHMARK_CLIP_DATA BENCHMARK_PROMPT_MANIFEST
export BENCHMARK_SOURCE_ROOT BENCHMARK_ENGINE
